-- ============================================================
-- tariff-book golongan project: table + indexes (run 1st)
-- ============================================================
-- A separate Supabase project that only holds the surgery classification
-- reference (golongan operasi). It is not a tarif shard: the API reads it
-- through GOLONGAN_URL / GOLONGAN_KEY, not SHARDS.
-- Run in the Supabase SQL Editor (role: postgres). Idempotent.
-- ============================================================

create extension if not exists pg_trgm;

-- Text order like the browser's (ICU, Indonesian): punctuation and symbols
-- such as "≥" sort the way users saw them in the old in-browser table.
create collation if not exists golongan_id (provider = icu, locale = 'id');

create table if not exists golongan_operasi (
  id           bigint generated by default as identity primary key,
  rumah_sakit  text not null,
  specialty    text not null,
  golongan     text not null,  -- KECIL, SEDANG 1, BESAR 2, KHUSUS 3, ... (no "OPERASI " prefix)
  service_code text,           -- hospital's own code; not every book has one
  nama_layanan text not null,
  -- the same line uploaded twice is rejected, also when service_code is empty
  constraint golongan_operasi_unique
    unique nulls not distinct (rumah_sakit, specialty, golongan, service_code, nama_layanan)
);

-- substring search on service name and specialty (ILIKE '%q%')
create index if not exists idx_golongan_nama_trgm on golongan_operasi using gin (nama_layanan gin_trgm_ops);
create index if not exists idx_golongan_spec_trgm on golongan_operasi using gin (specialty gin_trgm_ops);
create index if not exists idx_golongan_rs        on golongan_operasi (rumah_sakit);
