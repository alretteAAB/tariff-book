-- ============================================================
-- tariff-book golongan project: Clinical Pathway packages (run 4th)
-- ============================================================
-- Package prices per hospital, diagnosis and medical treatment, with the
-- items of each package (the "Clinical Pathway" tab). Lives in the golongan
-- project next to golongan_operasi; read through GOLONGAN_URL / GOLONGAN_KEY.
-- Loaded by scripts/upload_clinical_pathway.py, which calls cp_upload().
-- Run in the Supabase SQL Editor (role: postgres). Idempotent.
-- ============================================================

-- --- Tables ------------------------------------------------------
-- One row per card: hospital x diagnosis x medical treatment.
create table if not exists cp_paket (
  id                bigint generated by default as identity primary key,
  rumah_sakit       text not null,   -- e.g. "RS Mitra Keluarga Bekasi Timur"
  diagnosis         text not null,
  medical_treatment text,            -- empty for medical packages without a procedure
  icd10             text,
  tindakan          text,            -- package name as in the source file
  los               int,             -- length of stay, days
  constraint cp_paket_unique unique nulls not distinct (rumah_sakit, diagnosis, medical_treatment, icd10)
);
create index if not exists idx_cp_paket_rs on cp_paket (rumah_sakit);
-- shards created with the first version of this file had it NOT NULL
alter table cp_paket alter column medical_treatment drop not null;

-- Total package price per room class ("KELAS 1", "KELAS 2", "KELAS 3", "ODS").
-- 0 means the package is not offered (yet) at that hospital.
create table if not exists cp_harga (
  paket_id bigint not null references cp_paket(id) on delete cascade,
  kelas    text   not null,
  tarif    numeric not null,
  primary key (paket_id, kelas)
);

-- Items of a package, in source order. The same for every class.
create table if not exists cp_rincian (
  paket_id   bigint not null references cp_paket(id) on delete cascade,
  urut       int    not null,
  kegiatan   text,
  item       text,
  keterangan text,
  qty        numeric,
  primary key (paket_id, urut)
);

-- --- Helpers -----------------------------------------------------
-- Class order on the cards: Kelas 1, 2, 3, then ODS, then anything else.
create or replace function cp_kelas_rank(k text)
returns int language sql immutable as $$
  select case upper(k) when 'KELAS 1' then 1 when 'KELAS 2' then 2 when 'KELAS 3' then 3
                       when 'ODS' then 4 else 9 end;
$$;

-- --- RPC: filter lists -------------------------------------------
-- { rumah_sakit: [], diagnosis: [], medical_treatment: [],
--   relations: [{rumah_sakit, diagnosis, medical_treatment}] }
-- relations lets the page narrow one list by the others.
create or replace function cp_filters()
returns jsonb language sql stable as $$
  select jsonb_build_object(
    'rumah_sakit',       (select coalesce(jsonb_agg(v order by v), '[]') from (select distinct rumah_sakit v from cp_paket) x),
    'diagnosis',         (select coalesce(jsonb_agg(v order by v), '[]') from (select distinct diagnosis v from cp_paket) x),
    'medical_treatment', (select coalesce(jsonb_agg(v order by v), '[]')
                          from (select distinct medical_treatment v from cp_paket where medical_treatment is not null) x),
    'relations',         (select coalesce(jsonb_agg(jsonb_build_object(
                            'rumah_sakit', rumah_sakit, 'diagnosis', diagnosis, 'medical_treatment', medical_treatment)
                            order by rumah_sakit, diagnosis, medical_treatment), '[]')
                          from (select distinct rumah_sakit, diagnosis, medical_treatment from cp_paket) x)
  );
$$;

-- --- RPC: cards ---------------------------------------------------
-- Cards matching the filters (null = no filter), without their items. A
-- treatment filter only matches cards that have that treatment.
-- Cards:
-- [{id, rumah_sakit, diagnosis, medical_treatment, icd10, tindakan, los,
--   n_rincian, harga: [{kelas, tarif}]}]
create or replace function cp_search(
  f_rumah_sakit text[] default null,
  f_diagnosis   text[] default null,
  f_treatment   text[] default null
)
returns jsonb language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'id', p.id, 'rumah_sakit', p.rumah_sakit, 'diagnosis', p.diagnosis,
           'medical_treatment', p.medical_treatment, 'icd10', p.icd10,
           'tindakan', p.tindakan, 'los', p.los,
           'n_rincian', (select count(*) from cp_rincian r where r.paket_id = p.id),
           'harga', (select coalesce(jsonb_agg(jsonb_build_object('kelas', h.kelas, 'tarif', h.tarif)
                                               order by cp_kelas_rank(h.kelas), h.kelas), '[]')
                     from cp_harga h where h.paket_id = p.id))
         order by p.rumah_sakit, p.diagnosis, p.medical_treatment, p.icd10), '[]')
  from cp_paket p
  where (f_rumah_sakit is null or p.rumah_sakit       = any(f_rumah_sakit))
    and (f_diagnosis   is null or p.diagnosis         = any(f_diagnosis))
    and (f_treatment   is null or p.medical_treatment = any(f_treatment));
$$;

-- --- RPC: items of one card ----------------------------------------
-- [{kegiatan, item, keterangan, qty}] in source order.
create or replace function cp_rincian(f_paket_id bigint)
returns jsonb language sql stable as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'kegiatan', kegiatan, 'item', item, 'keterangan', keterangan, 'qty', qty)
         order by urut), '[]')
  from cp_rincian where paket_id = f_paket_id;
$$;

-- --- Upload (service_role only, see 03_security.sql / below) -------
-- Replaces every hospital named in payload.rumah_sakit with payload.paket,
-- in one transaction: an upload that fails half-way changes nothing, and
-- uploading the same file again gives the same result (no duplicates).
-- payload: { rumah_sakit: [..],
--            paket: [{rumah_sakit, diagnosis, medical_treatment, icd10, tindakan, los,
--                     harga: [{kelas, tarif}], rincian: [{kegiatan, item, keterangan, qty}]}] }
-- Returns { deleted, paket, harga, rincian } counts.
create or replace function cp_upload(payload jsonb)
returns jsonb language plpgsql as $$
declare
  v_deleted int;
  v_paket int := 0; v_harga int := 0; v_rincian int := 0;
  p jsonb;
  new_id bigint;
begin
  if exists (select 1 from jsonb_array_elements(payload->'paket') x
             where not (x->>'rumah_sakit' = any(array(select jsonb_array_elements_text(payload->'rumah_sakit'))))) then
    raise exception 'every paket.rumah_sakit must be listed in payload.rumah_sakit';
  end if;

  delete from cp_paket
  where rumah_sakit = any(array(select jsonb_array_elements_text(payload->'rumah_sakit')));
  get diagnostics v_deleted = row_count;

  for p in select * from jsonb_array_elements(payload->'paket') loop
    insert into cp_paket (rumah_sakit, diagnosis, medical_treatment, icd10, tindakan, los)
    values (p->>'rumah_sakit', p->>'diagnosis', p->>'medical_treatment', p->>'icd10',
            p->>'tindakan', (p->>'los')::int)
    returning id into new_id;
    v_paket := v_paket + 1;

    insert into cp_harga (paket_id, kelas, tarif)
    select new_id, h->>'kelas', (h->>'tarif')::numeric
    from jsonb_array_elements(p->'harga') h;
    v_harga := v_harga + jsonb_array_length(p->'harga');

    insert into cp_rincian (paket_id, urut, kegiatan, item, keterangan, qty)
    select new_id, r.n, r.v->>'kegiatan', r.v->>'item', r.v->>'keterangan', (r.v->>'qty')::numeric
    from jsonb_array_elements(p->'rincian') with ordinality as r(v, n);
    v_rincian := v_rincian + jsonb_array_length(p->'rincian');
  end loop;

  return jsonb_build_object('deleted', v_deleted, 'paket', v_paket, 'harga', v_harga, 'rincian', v_rincian);
end $$;

-- --- Access --------------------------------------------------------
-- Website (anon key): read only. Upload script (service_role): cp_upload.
do $$
declare t text;
begin
  foreach t in array array['cp_paket', 'cp_harga', 'cp_rincian'] loop
    execute format('drop policy if exists %I on %I', 'public read ' || t, t);
    execute format('create policy %I on %I for select to anon using (true)', 'public read ' || t, t);
    execute format('alter table %I enable row level security', t);
    execute format('revoke insert, update, delete, truncate on %I from anon, authenticated', t);
    execute format('grant select on %I to anon', t);
  end loop;
end $$;

grant execute on function cp_filters()                       to anon;
grant execute on function cp_search(text[], text[], text[])  to anon;
grant execute on function cp_rincian(bigint)                 to anon;
grant execute on function cp_kelas_rank(text)                to anon;
revoke execute on function cp_upload(jsonb) from public, anon, authenticated;
grant  execute on function cp_upload(jsonb) to service_role;
-- what cp_upload needs (Supabase grants these by default; explicit here)
grant select, insert, delete on cp_paket, cp_harga, cp_rincian to service_role;
grant usage on sequence cp_paket_id_seq to service_role;
