-- ============================================================
-- tariff-book shard: tables, view and indexes (run 1st)
-- ============================================================
-- Run in the Supabase SQL Editor (role: postgres) on every NEW shard.
-- Idempotent (if not exists / or replace). On shard 1 everything already
-- exists, so running it there changes nothing.
--
-- Mirrors the production schema as of 2026-10-14. Reference-table ids are
-- local to each shard: the same layanan name can have a different id on
-- shard 1 and shard 2. Scripts that move data map ids by name.
-- tarif_v2.id is generated per shard (the upload script does not send it);
-- moving a hospital gives its rows new ids on the target shard.
-- ============================================================

create extension if not exists pg_trgm;

-- --- Reference tables -------------------------------------------
create table if not exists rumah_sakit_ref (
  id   smallserial primary key,
  nama text not null unique
);

create table if not exists kategori_ref (
  id   smallserial primary key,
  nama text not null unique
);

create table if not exists kelas_kamar_ref (
  id   smallserial primary key,
  nama text not null unique
);

create table if not exists layanan_ref (
  id   serial primary key,
  nama text not null unique
);

-- Display name + group per hospital (keyed by rumah_sakit_ref.nama)
create table if not exists rumahsakit (
  rumah_sakit     text primary key,
  display_name    text not null,
  group_non_group text not null,
  nama_group      varchar(100)
);

-- Raw room class -> normalized room class (same content on every shard)
create table if not exists room_class_mapping (
  id                bigserial primary key,
  room_class        varchar(200) not null unique,
  mapped_room_class varchar(200) not null,
  created_at        timestamptz not null default now()
);

-- --- Fact table -------------------------------------------------
create table if not exists tarif_v2 (
  id             bigint generated by default as identity primary key,
  rumah_sakit_id smallint references rumah_sakit_ref(id),
  kategori_id    smallint references kategori_ref(id),
  kelas_kamar_id smallint references kelas_kamar_ref(id),
  layanan_id     integer  references layanan_ref(id),
  tahun          smallint,
  tarif          bigint,
  pct_increase   numeric,
  -- NULLS NOT DISTINCT: rows that only differ by an empty column (e.g. no
  -- kelas_kamar) still count as duplicates (see 05_strict_unique.sql)
  constraint tarif_v2_unique_combo
    unique nulls not distinct (rumah_sakit_id, kategori_id, kelas_kamar_id, layanan_id, tahun, tarif)
);

-- --- Indexes ----------------------------------------------------
-- Fuzzy + substring search on service names (ILIKE + <% operator)
create index if not exists idx_layanan_nama_trgm on layanan_ref using gin (nama gin_trgm_ops);

-- Self-join for pct_increase
create index if not exists idx_tarif_v2_join on tarif_v2 (layanan_id, kategori_id, kelas_kamar_id, tahun);

-- Filter-only queries (dropdowns without a keyword)
create index if not exists idx_tarif_v2_tahun    on tarif_v2 (tahun);
create index if not exists idx_tarif_v2_rs       on tarif_v2 (rumah_sakit_id);
create index if not exists idx_tarif_v2_kategori on tarif_v2 (kategori_id);
create index if not exists idx_tarif_v2_kelas    on tarif_v2 (kelas_kamar_id);

-- --- View: denormalized tarif over tarif_v2 + reference tables --
create or replace view tarif as
  select t.id,
         k.nama  as kategori_harga,
         l.nama  as nama_layanan,
         kk.nama as kelas_kamar,
         t.tarif,
         rs.nama as rumah_sakit,
         t.tahun,
         t.pct_increase
  from tarif_v2 t
  join rumah_sakit_ref rs     on rs.id = t.rumah_sakit_id
  join kategori_ref k         on k.id  = t.kategori_id
  left join kelas_kamar_ref kk on kk.id = t.kelas_kamar_id
  join layanan_ref l          on l.id  = t.layanan_id;
